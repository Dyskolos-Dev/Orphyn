// Generates native/crates/orphyn-native/src/design/icons.rs: the inner SVG markup of every lucide
// icon the React app imports (scanned in src/renderer/src), keyed by its import name in kebab case
// ("Disc3" -> "disc-3", "Volume2" -> "volume-2"). Run from the repository root after adding an icon to the React app:
//   node native/scripts/gen-icons.mjs
import fs from 'node:fs'
import path from 'node:path'

const lucide = path.resolve('node_modules/lucide-react/dist/esm')
const index = fs.readFileSync(path.join(lucide, 'lucide-react.mjs'), 'utf8')
const fileOf = new Map()
for (const m of index.matchAll(/export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)) {
  for (const part of m[1].split(',')) {
    const name = /as (\w+)/.exec(part)?.[1]
    if (name) fileOf.set(name, m[2])
  }
}

// Keyed by the React import name in kebab case ("Disc3" -> "disc-3", "Music" -> "music"), which
// is stable, while lucide renames its files ("music" now lives in "eighth-notes.mjs").
const kebab = (n) =>
  n.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])([0-9])/g, '$1-$2').toLowerCase()
const used = new Map()
for (const n of ['ChevronDown', 'Construction', 'ImageOff', 'X', 'Minus', 'Square', 'Copy', 'Check']) {
  used.set(kebab(n), fileOf.get(n))
}
function scan(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) scan(p)
    else if (/\.tsx?$/.test(e.name)) {
      const src = fs.readFileSync(p, 'utf8')
      for (const m of src.matchAll(/import\s*(?:type\s*)?\{([^}]+)\}\s*from\s*'lucide-react'/g)) {
        for (const part of m[1].split(',')) {
          const name = part.trim().split(/\s+as\s+/)[0]?.trim()
          const file = name && fileOf.get(name)
          if (file) used.set(kebab(name), file)
        }
      }
    }
  }
}
scan(path.resolve('src/renderer/src'))

function load(file) {
  const src = fs.readFileSync(path.join(lucide, 'icons', file + '.mjs'), 'utf8')
  if (src.includes('node: [')) return src
  const alias = /from '\.\/([a-z0-9-]+)\.mjs'/.exec(src)
  if (!alias) throw new Error('no icon data in ' + file)
  return load(alias[1])
}

function markup(file) {
  const src = load(file)
  const i = src.indexOf('node: [')
  let j = i + 'node: '.length
  const start = j
  let depth = 0
  do {
    if (src[j] === '[') depth++
    if (src[j] === ']') depth--
    j++
  } while (depth > 0)
  const nodes = eval(src.slice(start, j))
  return nodes
    .map(([tag, attrs]) => {
      const { key: _key, ...a } = attrs
      const list = Object.entries(a)
        .map(([k, v]) => k + '="' + v + '"')
        .join(' ')
      return '<' + tag + ' ' + list + '/>'
    })
    .join('')
}

const names = [...used.keys()].sort()
let out = '// Generated by native/scripts/gen-icons.mjs from lucide-react. Do not edit.\n'
out += '/// Inner SVG markup of a lucide icon by file name ("disc-3"), "" when unknown.\n'
out += "pub fn icon_markup(name: &str) -> &'static str {\n    match name {\n"
for (const n of names) out += '        ' + JSON.stringify(n) + ' => ' + JSON.stringify(markup(used.get(n))) + ',\n'
out += '        _ => "",\n    }\n}\n'
out += '\n/// Every icon name above (tests check the app only uses known ones).\n'
out += "pub const ICON_NAMES: &[&str] = &[\n" + names.map((n) => '    ' + JSON.stringify(n) + ',\n').join('') + '];\n'
fs.writeFileSync('native/crates/orphyn-native/src/design/icons.rs', out)
console.log(names.length + ' icons')
