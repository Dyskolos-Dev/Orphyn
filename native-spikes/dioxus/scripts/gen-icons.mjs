// Extracts the lucide icon nodes the spike uses into src/icons.rs (inner SVG markup strings).
// Run from the repository root: node native-spikes/dioxus/scripts/gen-icons.mjs
import fs from 'node:fs'
import path from 'node:path'

const dir = path.resolve('node_modules/lucide-react/dist/esm/icons')
const names = [
  'play', 'pause', 'shuffle', 'heart', 'skip-back', 'skip-forward', 'repeat', 'volume-2',
  'list-music', 'message-square-quote', 'chevron-down', 'chevron-left', 'chevron-right', 'music',
  'house', 'disc-3', 'mic-vocal', 'clapperboard', 'tv', 'circle-play', 'settings', 'search',
  'ellipsis', 'rotate-cw', 'maximize', 'arrow-left',
]

function load(name) {
  const src = fs.readFileSync(path.join(dir, name + '.mjs'), 'utf8')
  if (src.includes('node: ')) return src
  const alias = new RegExp("from './([a-z0-9-]+)\\.mjs'").exec(src)
  if (!alias) throw new Error('no icon data in ' + name)
  return load(alias[1])
}

let out = "// Generated by scripts/gen-icons.mjs from lucide-react. Do not edit.\n"
out += "pub fn icon_markup(name: &str) -> &'static str {\n    match name {\n"
for (const n of names) {
  const src = load(n)
  const i = src.indexOf('node: ')
  let depth = 0
  let j = i + 6
  do {
    if (src[j] === '[') depth++
    if (src[j] === ']') depth--
    j++
  } while (depth > 0)
  const nodes = eval(src.slice(i + 6, j))
  const markup = nodes
    .map(([tag, attrs]) => {
      const { key, ...a } = attrs
      const list = Object.entries(a).map(([k, v]) => k + '="' + v + '"').join(' ')
      return '<' + tag + ' ' + list + '/>'
    })
    .join('')
  out += '        ' + JSON.stringify(n) + ' => ' + JSON.stringify(markup) + ',\n'
}
out += '        _ => "",\n    }\n}\n'
fs.writeFileSync('native-spikes/dioxus/src/icons.rs', out)
